PRAGMA foreign_keys = ON;

DROP VIEW IF EXISTS CATALOGUE_INVENTORY;
DROP TABLE IF EXISTS STOCK_MOVEMENTS;
DROP TABLE IF EXISTS LOANS;
DROP TABLE IF EXISTS HOLDS;
DROP TABLE IF EXISTS COPIES;
DROP TABLE IF EXISTS CATALOGUE_ITEMS;
DROP TABLE IF EXISTS BRANCHES;
DROP TABLE IF EXISTS MEMBERS;

CREATE TABLE MEMBERS (
    id INTEGER PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE
);

CREATE TABLE CATALOGUE_ITEMS (
    id INTEGER PRIMARY KEY,
    title TEXT NOT NULL,
    author TEXT NOT NULL,
    item_type TEXT NOT NULL
        CHECK (item_type IN ('Book', 'Audiobook', 'E-book', 'Reference'))
);

CREATE TABLE BRANCHES (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    address TEXT,
    phone TEXT
);

CREATE TABLE HOLDS (
    id INTEGER PRIMARY KEY,
    member_id INTEGER NOT NULL,
    item_id INTEGER NOT NULL,
    placed_date TEXT NOT NULL,
    status TEXT NOT NULL
        CHECK (status IN ('Active', 'Cancelled', 'Completed')),
    FOREIGN KEY (member_id) REFERENCES MEMBERS(id),
    FOREIGN KEY (item_id) REFERENCES CATALOGUE_ITEMS(id)
);

CREATE TABLE COPIES (
    id INTEGER PRIMARY KEY,
    item_id INTEGER NOT NULL,
    branch_id INTEGER NOT NULL,
    condition TEXT NOT NULL
        CHECK (condition IN ('Good', 'Very good', 'Excellent', 'Fair')),
    is_available INTEGER NOT NULL DEFAULT 1
        CHECK (is_available IN (0, 1)),
    FOREIGN KEY (item_id) REFERENCES CATALOGUE_ITEMS(id),
    FOREIGN KEY (branch_id) REFERENCES BRANCHES(id)
);

CREATE TABLE LOANS (
    id INTEGER PRIMARY KEY,
    member_id INTEGER NOT NULL,
    copy_id INTEGER NOT NULL,
    loan_date TEXT NOT NULL,
    due_date TEXT NOT NULL,
    return_date TEXT,
    FOREIGN KEY (member_id) REFERENCES MEMBERS(id),
    FOREIGN KEY (copy_id) REFERENCES COPIES(id),
    CHECK (due_date >= loan_date),
    CHECK (return_date IS NULL OR return_date >= loan_date)
);

CREATE UNIQUE INDEX uq_one_active_loan_per_copy
ON LOANS(copy_id)
WHERE return_date IS NULL;

CREATE TABLE STOCK_MOVEMENTS (
    id INTEGER PRIMARY KEY,
    item_id INTEGER NOT NULL,
    branch_id INTEGER NOT NULL,
    movement_type TEXT NOT NULL
        CHECK (movement_type IN ('Arrival', 'Transfer', 'Return', 'Write-off')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    movement_date TEXT NOT NULL,
    notes TEXT,
    FOREIGN KEY (item_id) REFERENCES CATALOGUE_ITEMS(id),
    FOREIGN KEY (branch_id) REFERENCES BRANCHES(id)
);

